function localizeOffice(lang) {
    const fields = [["copy", "textContent"], ["title", "title"], ["aria-label", "aria-label"], ["placeholder", "placeholder"]];
    for (const [suffix, field] of fields) {
        for (const el of document.querySelectorAll("[data-ru-" + suffix + "]")) {
            const en = "data-en-" + suffix;
            if (!el.hasAttribute(en)) el.setAttribute(en, field === "textContent" ? el.textContent : el.getAttribute(field));
            const value = el.getAttribute((lang === "en" ? "data-en-" : "data-ru-") + suffix);
            if (field === "textContent") el.textContent = value;
            else el.setAttribute(field, value);
        }
    }
}
